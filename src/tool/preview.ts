export const rows = (state: string): Row[] => {
  if (state === 'empty') return [];
  const n = state === 'done' ? 4 : 5;
  return Array.from({ length: n }, (_, i) => {
    const st: Row['status'] = state === 'done' || i < 4 ? 'ok' : 'run';
    const [title, summary, text] = pieces[i % pieces.length];
    return {
      item: { id: `g_${i}`, name: i < 4 ? title : '收尾' },
      status: st,
      progress: st === 'run' ? 0.5 : st === 'ok' ? 1 : 0,
      result: st === 'ok' ? { title, summary: `${words(text)} · ${summary}`, text } : undefined,
    };
  });
};

